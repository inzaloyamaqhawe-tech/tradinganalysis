const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

test('private proof lifecycle, approval, renewal and subscription notifications', async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'trading-payments-'));
  for (const key of ['DB_HOST', 'MYSQL_HOST', 'DATABASE_URL', 'SMTP_HOST']) delete process.env[key];
  process.env.DATA_FILE = path.join(dir, 'accounts.json');
  process.env.BILLING_DATA_FILE = path.join(dir, 'billing.json');
  const { app, store, billing, checkExpiries } = require('../server');
  await store.init(); await billing.init();
  await store.setPassword('member@example.test', 'unused', { firstName: 'Test', lastName: 'Member', username: 'member123' });
  await store.setPassword('other@example.test', 'unused', { firstName: 'Other', lastName: 'Member', username: 'other123' });
  await store.setPassword('admin@example.test', 'unused', { firstName: 'Test', lastName: 'Admin', username: 'admin123' });
  await store.setAdmin('admin@example.test', 'elite_max', '2099-12-31T00:00:00.000Z');
  await store.createSession('member-token', 'member@example.test');
  await store.createSession('other-token', 'other@example.test');
  await store.createSession('admin-token', 'admin@example.test');
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  const api = (route, token = 'member-token', options = {}) => fetch(`${base}${route}`, { ...options, headers: { Authorization: `Bearer ${token}`, ...options.headers } });
  const upload = bytes => api('/api/payments/proof?plan=premium', 'member-token', { method: 'POST', headers: { 'Content-Type': 'application/octet-stream' }, body: bytes });
  const review = (action, proof) => api(`/api/admin/payments/${action}`, 'admin-token', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: proof.email, version: proof.version }) });
  try {
    assert.equal((await fetch(`${base}/api/payments/latest?email=member@example.test`)).status, 401);
    assert.equal((await api('/api/admin/payments')).status, 401);
    assert.equal((await upload(Buffer.from('<html>unsafe</html>'))).status, 400);
    assert.equal((await upload(Buffer.alloc(2 * 1024 * 1024 + 1))).status, 413);
    const firstResponse = await upload(Buffer.from('%PDF-1.4\nfirst-proof'));
    assert.equal(firstResponse.status, 200);
    const first = (await firstResponse.json()).proof;
    assert.equal(first.reference, 'member123'); assert.equal(first.status, 'pending');
    assert.equal(first.data, undefined);
    assert.equal((await store.getSubscriber(first.email)).status, 'pending');
    const second = (await (await upload(Buffer.from('%PDF-1.4\nreplacement-proof'))).json()).proof;
    assert.notEqual(second.version, first.version);
    assert.equal((await billing.listProofs()).length, 1);
    assert.equal((await review('approve', first)).status, 409);
    const link = `/api/admin/payments/proof?email=${encodeURIComponent(second.email)}&version=${second.version}`;
    assert.equal((await api(link)).status, 401);
    const download = await api(link, 'admin-token');
    assert.equal(download.status, 200); assert.match(download.headers.get('content-disposition'), /attachment/);
    assert.equal(await download.text(), '%PDF-1.4\nreplacement-proof');
    const approvals = await Promise.all([review('approve', second), review('approve', second)]);
    assert.deepEqual(approvals.map(r => r.status).sort(), [200, 409]);
    const subscriber = await store.getSubscriber(second.email);
    assert.equal(subscriber.plan, 'premium'); assert.equal(subscriber.status, 'active');
    assert.ok(new Date(subscriber.expires_at) > new Date(Date.now() + 29 * 86400000));
    const notices = await (await api('/api/notifications')).json();
    assert.equal(notices.notifications.length, 1);
    assert.match(notices.notifications[0].body, /Expiry:/);
    assert.equal((await (await api('/api/notifications/unread-count')).json()).subscription.plan, 'premium');
    assert.equal((await (await api('/api/notifications', 'other-token')).json()).notifications.length, 0);
    assert.equal((await (await api('/api/payments/latest', 'other-token')).json()).proof, null);
    const stats = await (await api('/api/admin/stats', 'admin-token')).json();
    assert.equal(stats.revenue.estimatedMRR, 45);
    const third = (await (await upload(Buffer.from('%PDF-1.4\nrenewal-proof'))).json()).proof;
    const renewed = await (await review('approve', third)).json();
    assert.ok(new Date(renewed.result.expiresAt) > new Date(Date.now() + 59 * 86400000));
    await store.activate(second.email, 2, 'premium');
    await checkExpiries(); await checkExpiries();
    assert.equal((await billing.notifications(second.email)).filter(n => n.title.includes('expires soon')).length, 1);
    const { createBilling } = require('../billing');
    const restored = createBilling({ mode: 'memory', store, file: process.env.BILLING_DATA_FILE });
    await restored.init();
    assert.equal((await restored.getProof(second.email)).version, third.version);
    await store.activate(second.email, -1, 'premium');
    await checkExpiries();
    const expiredNotices = await (await api('/api/notifications')).json();
    assert.ok(expiredNotices.notifications.some(n => n.title === 'Your subscription has expired'));
    assert.equal((await billing.getProof(second.email)).version, third.version);
    await api('/api/notifications/mark-all-read', 'member-token', { method: 'POST' });
    assert.equal((await (await api('/api/notifications/unread-count')).json()).count, 0);
    const fourth = (await (await upload(Buffer.from('%PDF-1.4\nrejected-proof'))).json()).proof;
    assert.equal((await review('reject', fourth)).status, 200);
    assert.equal((await billing.getProof(second.email)).status, 'rejected');
    assert.equal((await review('approve', fourth)).status, 409);
    const win = await store.logSignal({ instrument: 'BTC_USDT', side: 'BUY', created_at: '2026-10-12T12:00:00.000Z' });
    const beforeClose = await (await api('/api/dashboard-stats')).json();
    assert.equal(beforeClose.weekly.buy[0].winRate, null);
    await store.updateSignalOutcome(win.id, { status: 'closed', outcome: 'TP1' });
    const afterCloseResponse = await api('/api/dashboard-stats');
    assert.equal(afterCloseResponse.headers.get('cache-control'), 'no-store');
    const afterClose = await afterCloseResponse.json();
    assert.equal(afterClose.weekly.buy[0].winRate, 100);
    const loss = await store.logSignal({ instrument: 'BTC_USDT', side: 'BUY', created_at: '2026-10-12T14:00:00.000Z' });
    await store.updateSignalOutcome(loss.id, { status: 'closed', outcome: 'SL' });
    const latest = await (await api('/api/dashboard-stats')).json();
    assert.equal(latest.weekly.buy[0].winRate, 50);
    assert.ok(Number.isFinite(new Date(latest.updatedAt).getTime()));
  } finally {
    await new Promise(resolve => server.close(resolve));
    // The demo account store saves with a short debounce.
    await new Promise(resolve => setTimeout(resolve, 250));
    fs.rmSync(dir, { recursive: true, force: true });
  }
});
